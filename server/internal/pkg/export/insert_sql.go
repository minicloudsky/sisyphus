package export

import (
	"bufio"
	"encoding/hex"
	"fmt"
	"os"
	"strconv"
	"strings"
	"time"
	"unicode/utf8"
)

const insertBatchRows = 200

// ValidateExportTableName 校验导出 INSERT 的目标表名（字母数字下划线，可选 db.table）。
func ValidateExportTableName(name string) error {
	name = strings.TrimSpace(name)
	if name == "" {
		return nil
	}
	if len(name) > 200 {
		return fmt.Errorf("表名过长")
	}
	for _, part := range strings.Split(name, ".") {
		part = strings.TrimSpace(part)
		if part == "" {
			return fmt.Errorf("表名格式无效")
		}
		for _, r := range part {
			if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') || r == '_' {
				continue
			}
			return fmt.Errorf("表名仅允许字母、数字、下划线，可使用 db.table")
		}
	}
	return nil
}

func quoteMySQLIdent(name string) string {
	return "`" + strings.ReplaceAll(name, "`", "``") + "`"
}

// quoteMySQLTable 将 a.b 转为 `a`.`b`；空则 `query_export`。
func quoteMySQLTable(identPath string) string {
	identPath = strings.TrimSpace(identPath)
	if identPath == "" {
		return quoteMySQLIdent("query_export")
	}
	parts := strings.Split(identPath, ".")
	q := make([]string, 0, len(parts))
	for _, p := range parts {
		p = strings.TrimSpace(p)
		if p == "" {
			continue
		}
		q = append(q, quoteMySQLIdent(p))
	}
	if len(q) == 0 {
		return quoteMySQLIdent("query_export")
	}
	return strings.Join(q, ".")
}

func escapeSQLString(s string) string {
	s = strings.ReplaceAll(s, "\\", "\\\\")
	s = strings.ReplaceAll(s, "'", "\\'")
	s = strings.ReplaceAll(s, "\n", "\\n")
	s = strings.ReplaceAll(s, "\r", "\\r")
	s = strings.ReplaceAll(s, "\x00", "")
	return "'" + s + "'"
}

func formatMySQLSQLValue(v interface{}) string {
	if v == nil {
		return "NULL"
	}
	switch x := v.(type) {
	case []byte:
		if len(x) == 0 {
			return "''"
		}
		if utf8.Valid(x) {
			return escapeSQLString(string(x))
		}
		return "X'" + hex.EncodeToString(x) + "'"
	case string:
		return escapeSQLString(x)
	case int:
		return strconv.FormatInt(int64(x), 10)
	case int8:
		return strconv.FormatInt(int64(x), 10)
	case int16:
		return strconv.FormatInt(int64(x), 10)
	case int32:
		return strconv.FormatInt(int64(x), 10)
	case int64:
		return strconv.FormatInt(x, 10)
	case uint:
		return strconv.FormatUint(uint64(x), 10)
	case uint8:
		return strconv.FormatUint(uint64(x), 10)
	case uint16:
		return strconv.FormatUint(uint64(x), 10)
	case uint32:
		return strconv.FormatUint(uint64(x), 10)
	case uint64:
		return strconv.FormatUint(x, 10)
	case float32:
		return strconv.FormatFloat(float64(x), 'g', -1, 32)
	case float64:
		return strconv.FormatFloat(x, 'g', -1, 64)
	case bool:
		if x {
			return "1"
		}
		return "0"
	case time.Time:
		if x.IsZero() {
			return "NULL"
		}
		return "'" + x.Format("2006-01-02 15:04:05.000000") + "'"
	default:
		return escapeSQLString(fmt.Sprintf("%v", x))
	}
}

// ExportToInsertSQL 导出为 MySQL INSERT 语句（多行 VALUES 分批）。
func ExportToInsertSQL(data *ExportData, filePath string, tableName string) error {
	if err := ValidateExportTableName(tableName); err != nil {
		return err
	}
	tableName = strings.TrimSpace(tableName)
	tableSQL := quoteMySQLTable(tableName)

	f, err := os.Create(filePath)
	if err != nil {
		return err
	}
	defer f.Close()
	w := bufio.NewWriter(f)
	defer w.Flush()

	if _, err := fmt.Fprintf(w, "-- INSERT export generated by Sisyphus\n-- Target: %s\nSET NAMES utf8mb4;\n\n", tableSQL); err != nil {
		return err
	}
	if len(data.Columns) == 0 {
		_, err = w.WriteString("-- no columns\n")
		return err
	}

	colQuoted := make([]string, len(data.Columns))
	for i, c := range data.Columns {
		colQuoted[i] = quoteMySQLIdent(c)
	}
	colList := strings.Join(colQuoted, ", ")

	for start := 0; start < len(data.Rows); start += insertBatchRows {
		end := start + insertBatchRows
		if end > len(data.Rows) {
			end = len(data.Rows)
		}
		var sb strings.Builder
		sb.WriteString("INSERT INTO ")
		sb.WriteString(tableSQL)
		sb.WriteString(" (")
		sb.WriteString(colList)
		sb.WriteString(") VALUES\n")
		for i := start; i < end; i++ {
			if i > start {
				sb.WriteString(",\n")
			}
			sb.WriteString("(")
			row := data.Rows[i]
			for j := range data.Columns {
				if j > 0 {
					sb.WriteString(", ")
				}
				var val interface{}
				if j < len(row) {
					val = row[j]
				}
				sb.WriteString(formatMySQLSQLValue(val))
			}
			sb.WriteString(")")
		}
		sb.WriteString(";\n")
		if _, err := w.WriteString(sb.String()); err != nil {
			return err
		}
	}
	return nil
}
